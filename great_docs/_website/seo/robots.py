"""
Crawler rules and site-file references in `robots.txt`

The rules come from `seo.robots`. The file also points crawlers to `sitemap.xml` and to
`llms.txt` and `llms-full.txt` when the site publishes them.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Callable
    from pathlib import Path

    from ...config import Config

__all__ = ["write"]


def write(
    site_dir: Path,
    config: Config,
    base_url: str | None,
    *,
    report: Callable[[str], None],
) -> None:
    """
    Write `robots.txt` to the rendered site

    Include the configured rules for all crawlers, followed by any extra rules. With a base
    URL, also reference `sitemap.xml` when the sitemap is enabled, and `llms.txt` and
    `llms-full.txt` when those files exist. Write nothing when `robots.txt` is disabled or
    the site directory does not exist.

    Parameters
    ----------
    site_dir
        The rendered site.
    config
        Project configuration.
    base_url
        The site's canonical address, with a trailing slash, or `None` when it is unknown.
    report
        A callback that receives progress and skip messages. Disabling `robots.txt` produces
        no message.

    Returns
    -------
    :
        Nothing.
    """
    if not config.robots_enabled:
        return

    if not site_dir.exists():
        report("   ⚠️  _site directory not found, skipping robots.txt generation")
        return

    lines = ["# Robots.txt generated by Great Docs", "", "User-agent: *"]
    lines.append("Allow: /" if config.robots_allow_all else "Disallow: /")
    lines.extend(f"Disallow: {path}" for path in config.robots_disallow)

    crawl_delay = config.robots_crawl_delay
    if crawl_delay:
        lines.append(f"Crawl-delay: {crawl_delay}")

    lines.append("")

    extra_rules = config.robots_extra_rules
    if extra_rules:
        lines.append("# Additional rules")
        lines.extend(extra_rules)
        lines.append("")

    if base_url and config.sitemap_enabled:
        lines.append(f"Sitemap: {base_url}sitemap.xml")
        lines.append("")

    # Point AI agents to the context files the site publishes.
    if base_url:
        llms_names = [name for name in ("llms.txt", "llms-full.txt") if (site_dir / name).exists()]
        if llms_names:
            lines.append("# AI agent context files")
            lines.extend(f"Llms-txt: {base_url}{name}" for name in llms_names)
            lines.append("")

    _ = (site_dir / "robots.txt").write_text("\n".join(lines), encoding="utf-8")
    report("   Generated robots.txt")
