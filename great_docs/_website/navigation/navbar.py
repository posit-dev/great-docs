"""
Placement and order of the links on the navbar's left side

Great Docs identifies its own items (User Guide, Recipes, Reference, Changelog and Tags)
by `href`, so configuration options can name them by their English or translated label.
Other items match their label as written.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import TYPE_CHECKING, Any, cast

from ..._translations import translate

if TYPE_CHECKING:
    from ..._contribution import NavbarLink
    from ...config import Config

__all__ = [
    "CHANGELOG",
    "RECIPES",
    "REFERENCE",
    "TAGS",
    "USER_GUIDE",
    "OwnItem",
    "add_guide_link",
    "add_link",
    "has_item",
    "icon_labels",
    "reorder",
]


@dataclass(frozen=True)
class OwnItem:
    """A navbar item generated by Great Docs, labelled in the site's language"""

    english: str
    """The label on an English site"""

    key: str
    """The translation key of the label"""

    target: str
    """The item's exact `href`, or a directory prefix ending in `/`"""

    def label(self, config: Config) -> str:
        """
        Translate the item's label into the site's language

        Parameters
        ----------
        config
            The Great Docs configuration.

        Returns
        -------
        :
            The label the site shows.
        """
        return translate(self.key, config.lang)

    def owns(self, href: object) -> bool:
        """
        Check whether a navbar target belongs to this item

        Parameters
        ----------
        href
            The `href` of a navbar item.

        Returns
        -------
        :
            Whether `href` is the item's target or lies in its directory.
        """
        if not isinstance(href, str):
            return False
        if self.target.endswith("/"):
            return href.startswith(self.target)
        return href == self.target


USER_GUIDE = OwnItem("User Guide", "user_guide", "user-guide/")
RECIPES = OwnItem("Recipes", "recipes", "recipes/")
REFERENCE = OwnItem("Reference", "reference", "reference/")
CHANGELOG = OwnItem("Changelog", "changelog", "changelog.qmd")
TAGS = OwnItem("Tags", "tags", "tags/")

_OWN_ITEMS = (USER_GUIDE, RECIPES, REFERENCE, CHANGELOG, TAGS)


def add_link(
    quarto_config: dict[str, Any], link: NavbarLink, config: Config, *, after: str | None = None
) -> bool:
    """
    Add a link to the navbar's left side unless its `href` is already present

    The link follows the item named by `after`. Without `after`, or when no item
    matches it, the link precedes the Reference item, or goes last when there is none.
    The link's `before` target is not consulted.

    Parameters
    ----------
    quarto_config
        The Quarto configuration, changed in place.
    link
        The link to add.
    config
        The Great Docs configuration, which supplies the site's language for label matching.
    after
        The label of the item the link follows. Great Docs' own items match either
        their English or translated label.

    Returns
    -------
    :
        Whether the link was added. A configuration without `website.navbar.left`
        is left unchanged.
    """
    items = _left(quarto_config)
    if items is None or any(_field(item, "href") == link.href for item in items):
        return False
    anchor = _find(items, after, config) if after else None
    if anchor is not None:
        position = anchor + 1
    else:
        reference = _find_reference(items)
        position = len(items) if reference is None else reference
    items.insert(position, {"text": link.text, "href": link.href})
    return True


def add_guide_link(quarto_config: dict[str, Any], link: NavbarLink) -> bool:
    """
    Add the user guide's link to the navbar's left side unless its `href` is present

    Place the link before Reference, or first if Reference is absent. A link to another
    guide page does not prevent this addition.

    Parameters
    ----------
    quarto_config
        The Quarto configuration, changed in place.
    link
        The link to the guide's first page.

    Returns
    -------
    :
        Whether the link was added. A configuration without `website.navbar.left`
        is left unchanged.
    """
    items = _left(quarto_config)
    if items is None or any(_field(item, "href") == link.href for item in items):
        return False
    reference = _find_reference(items)
    items.insert(0 if reference is None else reference, {"text": link.text, "href": link.href})
    return True


def has_item(items: Sequence[object], href: str) -> bool:
    """
    Check whether the navbar's left side already has an item for a target

    Parameters
    ----------
    items
        Entries on the navbar's left side.
    href
        The target of a link that may be added.

    Returns
    -------
    :
        Whether an item has the same `href` or, when `href` belongs to one of Great Docs'
        own items, an `href` that belongs to the same item. A site has one Reference item,
        whether it opens the API or the command-line reference.
    """
    hrefs = [_field(item, "href") for item in items]
    if href in hrefs:
        return True
    own = next((item for item in _OWN_ITEMS if item.owns(href)), None)
    return own is not None and any(own.owns(existing) for existing in hrefs)


def reorder(quarto_config: dict[str, Any], config: Config) -> None:
    """
    Order the navbar's left side by the labels listed in `navbar_order`

    Listed items come first, in the listed order; the other labelled items follow in
    their current order. Great Docs' own items match either their English or translated
    label. Items without a label are dropped, and only one item per label is kept.

    Parameters
    ----------
    quarto_config
        The Quarto configuration, changed in place.
    config
        The Great Docs configuration.

    Returns
    -------
    :
    """
    order = config.navbar_order
    if not order:
        return
    navbar = cast("dict[str, Any]", quarto_config.get("website", {}).get("navbar", {}))
    left = cast("list[Any]", navbar.get("left", []))
    if not left:
        return

    # Duplicate labels keep the last item's contents at the first item's position.
    by_label: dict[Any, dict[str, Any]] = {}
    for item in left:
        if isinstance(item, dict) and "text" in item:
            entry = cast("dict[str, Any]", item)
            by_label[entry["text"]] = entry
    remaining = list(by_label.values())
    ordered: list[dict[str, Any]] = []
    for name in order:
        index = _find(remaining, name, config)
        if index is not None:
            ordered.append(remaining.pop(index))
    navbar["left"] = ordered + remaining


def icon_labels(icons: Mapping[str, str], config: Config) -> dict[str, str]:
    """
    Key the navbar icons by the labels the site shows

    Icons keyed by the English label of a Great Docs item gain its translated label
    as an additional key, unless `icons` already contains that key. The English key
    remains so items displaying the English label, such as a user's section titled
    `Changelog`, still receive the icon.

    Parameters
    ----------
    icons
        Icons keyed by navbar label.
    config
        The Great Docs configuration.

    Returns
    -------
    :
        The icons under their original keys, followed by the added translated keys.
    """
    labelled = dict(icons)
    for item in _OWN_ITEMS:
        if item.english in icons:
            _ = labelled.setdefault(item.label(config), icons[item.english])
    return labelled


def _find(items: Sequence[object], name: str, config: Config) -> int | None:
    """
    Find a navbar item by its English, translated or exact label

    Parameters
    ----------
    items
        Entries on the navbar's left side.
    name
        The label to match. For Great Docs' own items, either the English or translated
        label first matches by `href`. If no target matches, the label matches as written.
    config
        The Great Docs configuration.

    Returns
    -------
    :
        The position of the item, or `None` when no item matches.
    """
    for own in _OWN_ITEMS:
        if name in (own.english, own.label(config)):
            for index, item in enumerate(items):
                if own.owns(_field(item, "href")):
                    return index
            break
    for index, item in enumerate(items):
        if _field(item, "text") == name:
            return index
    return None


def _left(quarto_config: dict[str, Any]) -> list[Any] | None:
    """
    Find the entries on the navbar's left side

    Parameters
    ----------
    quarto_config
        The Quarto configuration.

    Returns
    -------
    :
        The list at `website.navbar.left`, or `None` when the configuration has none.
    """
    navbar = quarto_config.get("website", {}).get("navbar")
    if not navbar or "left" not in navbar:
        return None
    return cast("list[Any]", navbar["left"])


def _find_reference(items: Sequence[object]) -> int | None:
    """
    Find the Reference item by its `href`

    Parameters
    ----------
    items
        Entries on the navbar's left side.

    Returns
    -------
    :
        The position of the first item that opens a page under `reference/`, or `None`.
    """
    return next((i for i, item in enumerate(items) if REFERENCE.owns(_field(item, "href"))), None)


def _field(item: object, key: str) -> Any:
    """
    Read a field of a navbar item

    Parameters
    ----------
    item
        An entry of the navbar's left side.
    key
        The field, such as `text` or `href`.

    Returns
    -------
    :
        The field's value, or `None` when the item is not a mapping or lacks the field.
    """
    if not isinstance(item, dict):
        return None
    return cast("dict[str, Any]", item).get(key)
