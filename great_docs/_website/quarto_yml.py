"""
Read and write a build directory's `_quarto.yml`

Every write starts with the generated-file header and translates the navbar
labels that Great Docs generates in English.
"""

from __future__ import annotations

from collections.abc import Generator
from contextlib import contextmanager
from pathlib import Path
from typing import TYPE_CHECKING, Any, cast

from yaml12 import parse_yaml

from .._translations import get_translation
from .._utils import write_quarto_yml

if TYPE_CHECKING:
    from ..config import Config

FILENAME = "_quarto.yml"

# Generated navbar labels and their translation keys. A user-authored item
# with one of these labels is translated too.
_NAVBAR_LABELS = {
    "User Guide": "user_guide",
    "Recipes": "recipes",
    "Reference": "reference",
    "Changelog": "changelog",
}


def path(build_dir: Path) -> Path:
    """
    Return the path to a build directory's Quarto configuration

    Parameters
    ----------
    build_dir
        The Quarto project directory.

    Returns
    -------
    :
        The path to `_quarto.yml`, which may not exist yet.
    """
    return build_dir / FILENAME


def read(build_dir: Path, *, seed_website: bool = False) -> dict[str, Any]:
    """
    Parse a build directory's Quarto configuration

    An empty file reads as an empty mapping.

    Parameters
    ----------
    build_dir
        The Quarto project directory.
    seed_website
        Whether to treat a missing file as an empty mapping and supply missing
        `website` defaults: an empty `sidebar` list and a `navbar` mapping with
        an empty `left` list.

    Returns
    -------
    :
        The configuration.

    Raises
    ------
    FileNotFoundError
        If the file is missing and `seed_website` is false.
    """
    file = path(build_dir)
    if seed_website and not file.exists():
        quarto_config: dict[str, Any] = {}
    else:
        quarto_config = cast("dict[str, Any]", parse_yaml(file.read_text(encoding="utf-8")) or {})
    if seed_website:
        website = cast("dict[str, Any]", quarto_config.setdefault("website", {}))
        website.setdefault("sidebar", [])
        website.setdefault("navbar", {"left": []})
    return quarto_config


def write(build_dir: Path, quarto_config: dict[str, Any], config: Config) -> None:
    """
    Write a build directory's Quarto configuration

    Translate the generated navbar labels into the site's language and include
    the header that marks the build directory as generated.

    Parameters
    ----------
    build_dir
        The Quarto project directory.
    quarto_config
        The configuration, whose navbar labels are translated in place.
    config
        The Great Docs configuration.

    Returns
    -------
    :
    """
    _translate_navbar_labels(quarto_config, config.lang)
    write_quarto_yml(path(build_dir), quarto_config)


def write_initial(build_dir: Path, config: Config) -> None:
    """
    Write the website configuration that every build starts from

    The file's header marks the build directory as generated by Great Docs.
    A build that fails after this write can still be retried.

    Parameters
    ----------
    build_dir
        The Quarto project directory.
    config
        The Great Docs configuration.

    Returns
    -------
    :
    """
    write(
        build_dir, {"project": {"type": "website"}, "format": {"html": {"theme": "flatly"}}}, config
    )


@contextmanager
def edit(
    build_dir: Path, config: Config, *, seed_website: bool = False
) -> Generator[dict[str, Any]]:
    """
    Read the Quarto configuration for in-place changes and write it back

    Write the configuration when the block exits normally, including by
    `return`. Leave the file unchanged when the block raises.

    Parameters
    ----------
    build_dir
        The Quarto project directory.
    config
        The Great Docs configuration.
    seed_website
        Whether to treat a missing file as an empty mapping and supply missing
        `website` defaults: an empty `sidebar` list and a `navbar` mapping with
        an empty `left` list.

    Yields
    ------
    :
        The configuration to change in place.

    Raises
    ------
    FileNotFoundError
        If the file is missing and `seed_website` is false.
    """
    quarto_config = read(build_dir, seed_website=seed_website)
    yield quarto_config
    write(build_dir, quarto_config, config)


def _translate_navbar_labels(quarto_config: dict[str, Any], lang: str) -> None:
    """
    Translate the generated navbar labels in place

    Parameters
    ----------
    quarto_config
        The configuration.
    lang
        The site's language code.

    Returns
    -------
    :
    """
    if lang == "en":
        return
    navbar = cast("dict[str, Any]", quarto_config.get("website", {}).get("navbar", {}))
    for side in ("left", "right"):
        for item in cast("list[Any]", navbar.get(side, [])):
            if not isinstance(item, dict):
                continue
            entry = cast("dict[str, Any]", item)
            text = entry.get("text")
            if isinstance(text, str) and text in _NAVBAR_LABELS:
                entry["text"] = get_translation(_NAVBAR_LABELS[text], lang)
