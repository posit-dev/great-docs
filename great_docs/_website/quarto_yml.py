"""
Read and write a build directory's `_quarto.yml`, and apply a build step's `Contribution` to it

Every write starts with the generated-file header.
"""

from __future__ import annotations

from collections.abc import Generator, Iterable
from contextlib import contextmanager
from pathlib import Path
from typing import TYPE_CHECKING, Any, Literal, cast

from yaml12 import parse_yaml

from .._utils import write_quarto_yml
from . import inline_data
from .navigation import navbar as nav_navbar

if TYPE_CHECKING:
    from .._contribution import Contribution, NavbarLink, Sidebar
    from ..config import Config

FILENAME = "_quarto.yml"

RENDER_GLOBS = ("*.qmd", "*.md", "*.markdown", "*.rmd", "*.Rmd", "*.rmarkdown", "*.ipynb")
"""Quarto's default input files as per-extension globs, which match at any depth"""


def path(build_dir: Path) -> Path:
    """
    Return the path to a build directory's Quarto configuration

    Parameters
    ----------
    build_dir
        The Quarto project directory.

    Returns
    -------
    :
        The path to `_quarto.yml`, which may not exist yet.
    """
    return build_dir / FILENAME


def read(build_dir: Path, *, seed_website: bool = False) -> dict[str, Any]:
    """
    Parse a build directory's Quarto configuration

    An empty file reads as an empty mapping.

    Parameters
    ----------
    build_dir
        The Quarto project directory.
    seed_website
        Whether to treat a missing file as an empty mapping and supply missing
        `website` defaults: an empty `sidebar` list and a `navbar` mapping with
        an empty `left` list.

    Returns
    -------
    :
        The configuration.

    Raises
    ------
    FileNotFoundError
        If the file is missing and `seed_website` is false.
    """
    file = path(build_dir)
    if seed_website and not file.exists():
        quarto_config: dict[str, Any] = {}
    else:
        quarto_config = cast("dict[str, Any]", parse_yaml(file.read_text(encoding="utf-8")) or {})
    if seed_website:
        website = cast("dict[str, Any]", quarto_config.setdefault("website", {}))
        website.setdefault("sidebar", [])
        website.setdefault("navbar", {"left": []})
    return quarto_config


def write(build_dir: Path, quarto_config: dict[str, Any]) -> None:
    """
    Write a build directory's Quarto configuration

    The file includes the header that marks the build directory as generated.

    Parameters
    ----------
    build_dir
        The Quarto project directory.
    quarto_config
        The configuration.

    Returns
    -------
    :
    """
    write_quarto_yml(path(build_dir), quarto_config)


def write_initial(build_dir: Path) -> None:
    """
    Write the initial website configuration

    The file's header marks the build directory as generated by Great Docs.
    A build that fails after this write can still be retried.

    Parameters
    ----------
    build_dir
        The Quarto project directory.

    Returns
    -------
    :
    """
    write(build_dir, {"project": {"type": "website"}, "format": {"html": {"theme": "flatly"}}})


@contextmanager
def edit(build_dir: Path, *, seed_website: bool = False) -> Generator[dict[str, Any]]:
    """
    Read the Quarto configuration for in-place changes and write it back

    Write the updated configuration when the block exits normally, including
    by `return`. Preserve the file if the block raises an exception.

    Parameters
    ----------
    build_dir
        The Quarto project directory.
    seed_website
        Whether to treat a missing file as an empty mapping and supply missing
        `website` defaults: an empty `sidebar` list and a `navbar` mapping with
        an empty `left` list.

    Yields
    ------
    :
        The configuration to change in place.

    Raises
    ------
    FileNotFoundError
        If the file is missing and `seed_website` is false.
    """
    quarto_config = read(build_dir, seed_website=seed_website)
    yield quarto_config
    write(build_dir, quarto_config)


Slot = Literal["include-in-header", "include-after-body"]
"""An HTML format key whose entries Quarto adds to every page"""


def entries(mapping: dict[str, Any], key: str) -> list[Any]:
    """
    Return a configuration value as a list and store it under its key

    A missing or null value becomes an empty list; a single value becomes a
    one-item list. An existing list is reused. The returned list is stored
    under the key, so adding entries to it changes the configuration.

    Parameters
    ----------
    mapping
        The configuration mapping that holds the key, such as `project`.
    key
        The key, such as `resources`.

    Returns
    -------
    :
        The list stored under the key.
    """
    value = mapping.get(key)
    if value is None:
        items: list[Any] = []
    elif isinstance(value, list):
        items = cast("list[Any]", value)
    else:
        items = [value]
    mapping[key] = items
    return items


def includes(quarto_config: dict[str, Any], slot: Slot) -> list[Any]:
    """
    Return the HTML format's include list for one slot

    Parameters
    ----------
    quarto_config
        The configuration, changed in place to create the `format.html`
        mapping and include list if missing.
    slot
        The key for `include-in-header` or `include-after-body`.

    Returns
    -------
    :
        The list stored in the configuration.
    """
    html = cast("dict[str, Any]", quarto_config.setdefault("format", {})).setdefault("html", {})
    return entries(cast("dict[str, Any]", html), slot)


def find(items: list[Any], marker: str) -> int | None:
    """
    Find the first entry whose text contains a marker

    Entries are matched against their string representations. Quotes and line
    breaks may be escaped in those representations, so markers should contain
    neither.

    Parameters
    ----------
    items
        The entries, such as an include list.
    marker
        Text that identifies the entry, such as a script's file name.

    Returns
    -------
    :
        The entry's index, or `None` when no entry contains the marker.
    """
    return next((index for index, item in enumerate(items) if marker in str(item)), None)


def add_include(
    quarto_config: dict[str, Any],
    slot: Slot,
    entry: dict[str, str],
    *,
    marker: str | None = None,
    before: str | None = None,
) -> None:
    """
    Add an include entry unless it or an equivalent one is present

    Parameters
    ----------
    quarto_config
        The configuration, changed in place.
    slot
        The key for `include-in-header` or `include-after-body`.
    entry
        The entry to add, such as `{"text": "<script src=...>"}`.
    marker
        Text that identifies an equivalent entry, or `None` to look only for an
        equal entry.
    before
        Text that identifies the entry this one must precede. The entry is
        appended when `before` is `None` or no entry contains it.

    Returns
    -------
    :
    """
    items = includes(quarto_config, slot)
    if entry in items or (marker is not None and find(items, marker) is not None):
        return
    position = find(items, before) if before is not None else None
    items.insert(len(items) if position is None else position, entry)


def set_include(
    quarto_config: dict[str, Any], slot: Slot, entry: dict[str, str], *, marker: str
) -> None:
    """
    Replace matching includes at the first match's position, or append if none match

    Replace the first entry containing `marker` with `entry` and remove later matches.
    Repeated calls preserve the entry's position.

    Parameters
    ----------
    quarto_config
        The configuration, changed in place.
    slot
        The key for `include-in-header` or `include-after-body`.
    entry
        The entry to set, such as `{"text": "<meta name=...>"}`.
    marker
        Text matched against each entry's string representation. Avoid quotes and line
        breaks, which may be escaped.

    Returns
    -------
    :
    """
    items = includes(quarto_config, slot)
    position = find(items, marker)
    if position is None:
        items.append(entry)
        return
    items[position + 1 :] = [item for item in items[position + 1 :] if marker not in str(item)]
    items[position] = entry


def add_resources(quarto_config: dict[str, Any], names: Iterable[str]) -> None:
    """
    List files in `project.resources` for Quarto to copy into the site

    Names are appended in the supplied order, excluding those already listed.

    Parameters
    ----------
    quarto_config
        The configuration, changed in place.
    names
        The file names or globs, relative to the project directory.

    Returns
    -------
    :
    """
    project = cast("dict[str, Any]", quarto_config.setdefault("project", {}))
    resources = entries(project, "resources")
    for name in names:
        if name not in resources:
            resources.append(name)


def add_render_excludes(quarto_config: dict[str, Any], names: Iterable[str]) -> None:
    """
    Exclude files from rendering by adding `!` patterns to `project.render`

    Patterns are appended in the supplied order, excluding those already listed. A
    missing render list is first filled with `RENDER_GLOBS`, so Quarto still renders
    its default inputs. A recursive `**` would not do: it overrides the exclusions that
    follow it (issue #228).

    Parameters
    ----------
    quarto_config
        The configuration, changed in place.
    names
        The file names or globs to exclude, relative to the project directory.

    Returns
    -------
    :
    """
    project = cast("dict[str, Any]", quarto_config.setdefault("project", {}))
    if project.get("render") is None:
        project["render"] = list(RENDER_GLOBS)
    render = entries(project, "render")
    for name in names:
        exclude = f"!{name}"
        if exclude not in render:
            render.append(exclude)


def apply(quarto_config: dict[str, Any], contribution: Contribution, config: Config) -> None:
    """
    Add a build step's navigation, resources, render exclusions and script data

    Assign each inline data entry to a global in `format.html.include-after-body`,
    before the first entry containing its `before` text, or last if none matches.
    Preserve the value of any global already assigned.

    Add links to `website.navbar.left` according to their kind:

    - Skip a `generated` link if an item has the same `href` or, for Great Docs' own
      items such as Reference, a target in the same directory. Place it before the first
      item whose `href` matches `before`, or last if no target is set or found.
    - Skip an `authored` link only if an item has the same `href`. Place it after the
      item labelled `after`, before Reference if no label matches, or last if neither
      is found.
    - Skip a `user_guide` link only if an item has the same `href`. Place it before
      Reference, or first if Reference is absent.

    Repeated contributions add each link only once. Configurations without
    `website.navbar.left` get no links.

    Append each sidebar to `website.sidebar` after removing every entry with the same
    `id`. Create the list if missing, and omit the `title` key for untitled sidebars.

    Add resources to `project.resources` and render exclusions to `project.render`,
    each once, as `add_resources` and `add_render_excludes` do.

    Parameters
    ----------
    quarto_config
        The configuration, changed in place.
    contribution
        The navigation, resources, render exclusions and script data to add.
    config
        The Great Docs configuration. Its language determines which translated labels
        match an `authored` link's `after` value.

    Returns
    -------
    :
    """
    # Assign data before adding links to preserve the tags step's configuration key order
    # when the assignment creates `format`.
    for item in contribution.inline_data:
        inline_data.add(quarto_config, item.name, item.data, before=item.before)
    _add_navbar_links(quarto_config, contribution.navbar, config)
    if contribution.sidebars:
        _add_sidebars(quarto_config, contribution.sidebars)
    if contribution.resources:
        add_resources(quarto_config, contribution.resources)
    if contribution.render_excludes:
        add_render_excludes(quarto_config, contribution.render_excludes)


def _add_navbar_links(
    quarto_config: dict[str, Any], links: Iterable[NavbarLink], config: Config
) -> None:
    """
    Add missing links to the navbar's left side

    Parameters
    ----------
    quarto_config
        The configuration, changed in place.
    links
        The links, in order.
    config
        The Great Docs configuration, which supplies the language for `after` matching.

    Returns
    -------
    :
    """
    navbar = quarto_config.get("website", {}).get("navbar")
    if not navbar or "left" not in navbar:
        return
    items = cast("list[Any]", navbar["left"])
    for link in links:
        if link.kind == "authored":
            _ = nav_navbar.add_link(quarto_config, link, config, after=link.after)
            continue
        if link.kind == "user_guide":
            _ = nav_navbar.add_guide_link(quarto_config, link)
            continue
        if nav_navbar.has_item(items, link.href):
            continue
        hrefs = [
            cast("dict[str, Any]", item).get("href") if isinstance(item, dict) else None
            for item in items
        ]
        before = link.before
        position = hrefs.index(before) if before is not None and before in hrefs else len(items)
        items.insert(position, {"text": link.text, "href": link.href})


def _add_sidebars(quarto_config: dict[str, Any], sidebars: Iterable[Sidebar]) -> None:
    """
    Append sidebars, removing earlier entries with the same `id`

    Parameters
    ----------
    quarto_config
        The configuration, changed in place.
    sidebars
        The sidebars, in order.

    Returns
    -------
    :
    """
    website = cast("dict[str, Any]", quarto_config.setdefault("website", {}))
    existing = entries(website, "sidebar")
    for sidebar in sidebars:
        entry: dict[str, Any] = {"id": sidebar.id}
        if sidebar.title is not None:
            entry["title"] = sidebar.title
        entry["contents"] = list(sidebar.contents)
        existing[:] = [
            item
            for item in existing
            if not (isinstance(item, dict) and cast("dict[str, Any]", item).get("id") == sidebar.id)
        ]
        existing.append(entry)
