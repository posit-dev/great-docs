def test_for_page_rebases_links_marks_current_and_opens_sections():
    script = _load_script()
    nav = script._for_page(_NAV, "reference/gd-sidebar-reference.html", "reference/sub/b.html")

    assert 'href="../../reference/index.html" class="sidebar-item-text sidebar-link">' in nav
    assert 'href="../../reference/sub/b.html" class="sidebar-item-text sidebar-link active">' in nav
    assert 'class="collapse list-unstyled sidebar-section depth2 show">' in nav
    assert "collapsed" not in nav
    assert 'aria-expanded="false"' not in nav


def test_for_page_leaves_other_sections_closed():
    script = _load_script()
    nav = script._for_page(_NAV, "reference/gd-sidebar-reference.html", "reference/index.html")

    assert 'href="../reference/index.html" class="sidebar-item-text sidebar-link active">' in nav
    assert nav.count(" active") == 1
    assert 'sidebar-section depth2 ">' in nav
    assert nav.count('aria-expanded="false"') == 2


def test_share_keeps_template_while_previewing(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    script = _load_script()
    monkeypatch.setattr(script, "cache_dir", tmp_path / "_gd_sidebars")
    site = tmp_path / "_site"
    template = site / "reference" / "gd-sidebar-reference.html"
    page = site / "reference" / "sub" / "b.html"
    page.parent.mkdir(parents=True)
    html = '<body><nav id="quarto-sidebar" class="sidebar">{}</nav></body>'
    sidebar = {"id": "reference", "template": "reference/gd-sidebar-reference.html"}
    sidebar["pages"] = ["reference/sub/b.html"]

    # `quarto preview` reads the template after the script runs
    monkeypatch.setenv(shared_sidebar.PREVIEW_ENV, "1")
    for previewing in (True, False):
        if not previewing:
            monkeypatch.delenv(shared_sidebar.PREVIEW_ENV)
        template.write_text(html.format(_NAV), encoding="utf-8")
        page.write_text(html.format(""), encoding="utf-8")

        assert script._share(sidebar, site, None) == 1
        assert template.exists() is previewing
        assert 'sub/b.html" class="sidebar-item-text sidebar-link active"' in page.read_text()


def test_for_page_without_its_own_link_only_rebases():
    script = _load_script()
    nav = script._for_page(_NAV, "reference/gd-sidebar-reference.html", "reference/other.html")

    assert nav == _NAV


# ── Rendering with Quarto ────────────────────────────────────────────────────

_needs_quarto = pytest.mark.skipif(shutil.which("quarto") is None, reason="Quarto not installed")

_SIDEBAR_NAV = re.compile(r'<nav id="quarto-sidebar".*?</nav>', re.S)


def _render(root: Path, *args: str) -> None:
    subprocess.run(["quarto", "render", *args], cwd=root, check=True, capture_output=True)


def _search(site: Path) -> list[dict]:
    entries = json.loads((site / "search.json").read_text(encoding="utf-8"))
    return sorted(entries, key=lambda e: e["objectID"])


@pytest.fixture(scope="module")
def sites(tmp_path_factory: pytest.TempPathFactory) -> tuple[Path, Path]:
    plain = _write_project(tmp_path_factory.mktemp("plain") / "proj")
    shared = _write_project(tmp_path_factory.mktemp("shared") / "proj")
    assert shared_sidebar.prepare(shared) == ["reference", "cli-reference"]
    _render(plain)
    _render(shared)
    return plain / "_site", shared / "_site"


@_needs_quarto
@pytest.mark.parametrize("page", [n.replace(".qmd", ".html") for n in _PAGES if n.endswith(".qmd")])
def test_rendered_pages_match_plain_render(sites: tuple[Path, Path], page: str):
    plain, shared = sites

    assert (shared / page).read_text(encoding="utf-8") == (plain / page).read_text(encoding="utf-8")


@_needs_quarto
def test_rendered_pages_show_full_sidebar(sites: tuple[Path, Path]):
    _, shared = sites
    nav = _SIDEBAR_NAV.search((shared / "reference" / "Frame.select.html").read_text()).group(0)

    assert nav.count('<a href="') == 5
    assert (
        'href="../reference/Frame.select.html" class="sidebar-item-text sidebar-link active"' in nav
    )


@_needs_quarto
def test_rendered_search_index_matches_plain_render(sites: tuple[Path, Path]):
    plain, shared = sites

    assert _search(shared) == _search(plain)


@_needs_quarto
def test_rendered_site_drops_templates(sites: tuple[Path, Path]):
    plain, shared = sites

    assert sorted(p.relative_to(shared) for p in shared.rglob("*.html")) == sorted(
        p.relative_to(plain) for p in plain.rglob("*.html")
    )
    assert "gd-sidebar-" not in (shared / "sitemap.xml").read_text(encoding="utf-8")


@_needs_quarto
def test_rerendering_one_page_reuses_cached_sidebar(sites: tuple[Path, Path]):
    plain, shared = sites
    page = shared / "reference" / "cli" / "group" / "run.html"
    page.unlink()

    # As `quarto preview` does after an edit, render only the changed page
    _render(shared.parent, "reference/cli/group/run.qmd")

    assert page.read_text(encoding="utf-8") == (
        plain / "reference" / "cli" / "group" / "run.html"
    ).read_text(encoding="utf-8")
