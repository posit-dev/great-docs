"""
Reference sidebars rendered once and copied into their pages

`shared_sidebar.prepare()` trims each long reference sidebar before Quarto
renders the project, and `share-sidebars.py` copies the full sidebar into the
pages afterwards. The rendered pages and search index must match those of a
plain Quarto render.
"""

