def test_prepare_reads_options_from_directory_metadata(tmp_path: Path):
    pages = {
        name: text.replace(_REFERENCE, "")
        for name, text in _PAGES.items()
        if name != "reference/_metadata.yml"
    }
    # A page that shows no sidebar stays that way under the directory's metadata
    pages["reference/plain.qmd"] = "---\ntitle: Plain\nsidebar: false\n---\n\nText.\n"
    pages["reference/_metadata.yaml"] = _REFERENCE
    pages["reference/cli/_metadata.yml"] = _REFERENCE
    root = _write_project(tmp_path / "proj", pages=pages)

    assert shared_sidebar.prepare(root) == ["reference", "cli-reference"]
    # The directory's own metadata file gains the sidebar
    assert not (root / "reference" / "_metadata.yml").exists()
    assert yaml.safe_load((root / "reference" / "_metadata.yaml").read_text()) == {
        "page-navigation": False,
        "bread-crumbs": False,
        "sidebar": "reference",
    }


def test_prepare_leaves_out_crumbs_it_cant_work_out(tmp_path: Path):
    quarto_yml = _QUARTO_YML.replace(
        "  navbar:\n    left:\n",
        "  search:\n    merge-navbar-crumbs: false\n"
        "  navbar:\n    left:\n      - text: More\n        menu:\n          - guide.qmd\n",
    )
    # A bare link to a page without a title has no crumb text
    pages = {**_PAGES, "reference/load.qmd": f"---\n{_REFERENCE}---\n\nLoad.\n"}
