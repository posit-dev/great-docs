#!/usr/bin/env python3
"""
Signature highlighting grammar for Quarto

Generate `great_docs/assets/pythonsignature.xml` as a KDE syntax definition for
`pythonsignature` code blocks. Classify builtins, exceptions, keywords and word
operators using Pygments' `PythonLexer`. The installed Pygments version determines
the output; the running Python version does not affect it. Repeated runs with
the same Pygments version produce identical bytes.
"""

from __future__ import annotations

import keyword
from collections import defaultdict
from pathlib import Path
from xml.sax.saxutils import escape

import pygments
from pygments.lexer import words
from pygments.lexers.python import PythonLexer
from pygments.token import STANDARD_TYPES

OUTPUT = Path(__file__).resolve().parent.parent / "great_docs" / "assets" / "pythonsignature.xml"

# The lexer recognises these names outside its word lists.
EXTRA_WORDS = {"self", "cls", "Ellipsis", "NotImplemented"}

# A Python identifier, which may hold non-ASCII letters. Skylighting's `\w`
# matches them.
IDENT = r"[^\W\d]\w*"


def _candidate_words() -> set[str]:
    """
    Collect candidate identifiers for the grammar's word lists

    Returns
    -------
    :
        Identifiers from the lexer's word lists, Python's keywords and the
        additional names the lexer recognises outside its word lists.
    """
    found = set(keyword.kwlist) | EXTRA_WORDS
    for rules in PythonLexer.tokens.values():
        for rule in rules:
            if isinstance(rule, tuple) and isinstance(rule[0], words):
                found.update(rule[0].words)
    # Multi-word entries such as `yield from` cannot be grammar keywords.
    return {w for w in found if w.isidentifier()}


def _classify(candidates: set[str]) -> dict[str, list[str]]:
    """
    Group words by their Pygments token class in a default argument

    Parameters
    ----------
    candidates
        Words to classify.

    Returns
    -------
    :
        Sorted word lists keyed by Pygments' short token class, such as `nb` or `kc`.
    """
    lexer = PythonLexer()
    classes: defaultdict[str, list[str]] = defaultdict(list)
    for word in sorted(candidates):
        for token, value in lexer.get_tokens(f"f(x={word})"):
            if value == word:
                classes[STANDARD_TYPES[token]].append(word)
                break
    return classes


def _word_list(name: str, items: list[str]) -> str:
    """
    Return a grammar `<list>` element with sorted, XML-escaped items

    Parameters
    ----------
    name
        List name referenced by the grammar's rules.
    items
        Words in the list.

    Returns
    -------
    :
        The XML element on one line, followed by a newline.
    """
    body = "".join(f"<item>{escape(w)}</item>" for w in sorted(items))
    return f'    <list name="{name}">{body}</list>\n'


def make_grammar() -> str:
    """
    Generate the signature grammar using the installed Pygments version

    Returns
    -------
    :
        The KDE syntax definition as XML.
    """
    classes = _classify(_candidate_words())
    constants = classes["kc"]
    lists = (
        _word_list("nones", [w for w in constants if w == "None"])
        + _word_list("bools", [w for w in constants if w != "None"])
        + _word_list("builtins", classes["nb"] + classes["bp"])
        + _word_list("exceptions", classes["ne"])
        + _word_list("keywords", classes["k"])
        + _word_list("wordops", classes["ow"])
    )
    return f"""\
<?xml version="1.0" encoding="UTF-8"?>
<!--
  Generated by scripts/make_signature_grammar.py from Pygments {pygments.__version__}.
  Do not edit by hand. Run `make signature-grammar` to regenerate it.
-->
<!DOCTYPE language>
<language name="pythonsignature" section="Sources" version="1" kateversion="5.0" extensions="*.pythonsignature">
  <highlighting>
{lists}    <contexts>
      <context name="Start" attribute="Normal" lineEndContext="#stay">
        <RegExpr attribute="Class" String="{IDENT}(?=\\.{IDENT}(\\(|$))" column="0" context="Qualified"/>
        <RegExpr attribute="Name" String="{IDENT}(?=\\(|$)" column="0"/>
        <keyword attribute="None" String="nones"/>
        <keyword attribute="Bool" String="bools"/>
        <keyword attribute="Builtin" String="builtins"/>
        <keyword attribute="Exception" String="exceptions"/>
        <keyword attribute="Keyword" String="keywords"/>
        <keyword attribute="Operator" String="wordops"/>
        <RegExpr attribute="StringPrefix" String="[bBrRuUfF]{{1,2}}(?=[&quot;'])"/>
        <RegExpr attribute="Variable" String="{IDENT}"/>
        <RegExpr attribute="Float" String="(\\d+\\.\\d*|\\.\\d+)([eE][+-]?\\d+)?|\\d+[eE][+-]?\\d+"/>
        <RegExpr attribute="Int" String="\\d+"/>
        <DetectChar attribute="String" char="&quot;" context="DQ"/>
        <DetectChar attribute="String" char="'" context="SQ"/>
        <AnyChar attribute="Operator" String="=*/|-+.&lt;&gt;%&amp;^~@!"/>
      </context>
      <context name="Qualified" attribute="Normal" lineEndContext="#pop">
        <DetectChar attribute="Operator" char="."/>
        <RegExpr attribute="Name" String="{IDENT}" context="#pop"/>
      </context>
      <context name="DQ" attribute="String" lineEndContext="#pop">
        <HlCStringChar attribute="String"/>
        <DetectChar attribute="String" char="&quot;" context="#pop"/>
      </context>
      <context name="SQ" attribute="String" lineEndContext="#pop">
        <HlCStringChar attribute="String"/>
        <DetectChar attribute="String" char="'" context="#pop"/>
      </context>
    </contexts>
    <itemDatas>
      <itemData name="Normal" defStyleNum="dsNormal"/>
      <itemData name="Name" defStyleNum="dsFunction"/>
      <itemData name="Class" defStyleNum="dsDataType"/>
      <itemData name="Variable" defStyleNum="dsVariable"/>
      <itemData name="Builtin" defStyleNum="dsBuiltIn"/>
      <itemData name="Exception" defStyleNum="dsExtension"/>
      <itemData name="Keyword" defStyleNum="dsKeyword"/>
      <itemData name="None" defStyleNum="dsConstant"/>
      <itemData name="Bool" defStyleNum="dsBaseN"/>
      <itemData name="Int" defStyleNum="dsDecVal"/>
      <itemData name="Float" defStyleNum="dsFloat"/>
      <itemData name="String" defStyleNum="dsString"/>
      <itemData name="StringPrefix" defStyleNum="dsExtension"/>
      <itemData name="Operator" defStyleNum="dsOperator"/>
    </itemDatas>
  </highlighting>
  <general>
    <keywords casesensitive="1"/>
  </general>
</language>
"""


def main() -> None:
    """
    Write the grammar to `great_docs/assets/pythonsignature.xml`
    """
    OUTPUT.write_text(make_grammar(), encoding="utf-8")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
